package com.draftpeek.feature.stats.model

/**
 * 统计时间范围枚举。
 *
 * 提供预设的时间范围选项，用于在统计页面筛选不同时间段的活动数据。
 */
enum class TimeRange {
    /** 全部时间 - 统计所有历史数据 */
    ALL,

    /** 最近 30 天 */
    D30,

    /** 最近 7 天 */
    D7
}

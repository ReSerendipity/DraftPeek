package com.draftpeek.core.sync

/**
 * 同步的可见状态。
 *
 * 设计回函 v3 §3：同步中 / 失败 / 离线三态**一律行内提示，不弹窗**；
 * 弹窗留给冲突处理（阶段 B 设计稿）。
 */
enum class SyncPhase {
    /** 尚未同步过，且当前没有进行中的同步。 */
    IDLE,

    /** 正在同步。此期间重复触发被忽略（规格：禁用重复触发）。 */
    SYNCING,

    /** 上次同步成功。 */
    SYNCED,

    /** 同步失败，等待用户手动重试。 */
    FAILED,

    /** 离线：恢复联网后**自动续传**。 */
    OFFLINE
}

/**
 * 同步失败的原因分类 —— 决定**是否值得退避重试**。
 *
 * 方案 C（用户自己的 Git 仓库）下，`AUTH` / `REPOSITORY` 两类是新增的、
 * 由 Git 载体带来的失败形态（授权过期、仓库权限/配额/不存在）。
 */
enum class SyncFailureKind {
    /** 网络类：可退避重试（1s → 4s → 16s）。 */
    NETWORK,

    /** 授权类：token 失效或被撤销 —— 重试无意义，需重新授权。 */
    AUTH,

    /** 仓库类：无 repo 权限 / 配额用尽 / 仓库不存在 —— 重试无意义。 */
    REPOSITORY,

    /**
     * 冲突类：远端在我们上次拉取之后被别人改动过（Git Contents API 返回 409）。
     *
     * 与其余几类的区别：它**不是失败**，而是「需要先重新拉取并合并」的信号。
     * 设计回函 v3 §3 明确「冲突是唯一留给弹窗的场景」。
     */
    CONFLICT,

    /** 其他未归类失败。 */
    OTHER
}
